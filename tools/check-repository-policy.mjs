// Temporary generic preservation controls; ownership/retirement: PROVENANCE.md.
import { execFileSync } from 'node:child_process';
import { lstatSync, readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, posix, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const decoder = new TextDecoder('utf-8', { fatal: true });
export const requiredFiles = ['AGENTS.md', 'CONTRIBUTING.md', 'README.md', 'LICENSE', 'SECURITY.md', 'CATALOG.md'];
const snapshotPath = 'repository-structure.txt';

export function repositoryFiles(root) {
  const output = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { cwd: root });
  return [...new Set(decoder.decode(output).split('\0').filter(Boolean))].sort();
}

function components(files) {
  return [...new Set(files.flatMap(file => {
    const parts = file.split('/');
    return parts.map((_, index) => parts.slice(0, index + 1).join('/'));
  }))].sort();
}

// Complete this metadata-only pass before reading any validation input. Checking
// ancestors first prevents an otherwise ordinary tracked file following a link.
export function assertSafeInputs(root, files) {
  for (const file of components([...files, snapshotPath])) {
    const path = resolve(root, file);
    const fromRoot = relative(resolve(root), path);
    if (fromRoot === '..' || fromRoot.startsWith(`..${sep}`) || isAbsolute(fromRoot)) throw new Error(`${file}: path escapes repository`);
    let metadata;
    try { metadata = lstatSync(path); }
    catch (error) {
      if (file === snapshotPath && !files.includes(file) && error.code === 'ENOENT') continue;
      throw new Error(`${file}: metadata unavailable (${error.code})`);
    }
    if (metadata.isSymbolicLink()) throw new Error(`${file}: symbolic links are not allowed`);
    if (!metadata.isFile() && !metadata.isDirectory()) throw new Error(`${file}: unsupported input type`);
  }
}

export function validName(path, isFile = true) {
  const name = posix.basename(path);
  if (/^\.(?:github|githooks|vscode)(?:\/|$)/u.test(path)) return true;
  if (isFile && name === 'README.md') return true;
  if (/^(?:scripts|tests)\/[^/]+\.py$/u.test(path)) {
    return /^(?:[a-z][a-z0-9]*(?:_[a-z0-9]+)*|__init__)\.py$/u.test(name);
  }
  if (/^templates\/[^/]+\/(?:README\.md|standard\.md)$/u.test(path)) return true;
  if (!path.includes('/') && (path.endsWith('.md') || ['LICENSE', '.editorconfig', '.gitattributes', '.gitignore', '.markdownlint-cli2.jsonc', '.pre-commit-config.yaml', 'scripts', 'tests'].includes(path))) return true;
  return /^[a-z0-9]+(?:-[a-z0-9]+)*(?:\.[a-z0-9]+)*$/u.test(name);
}

export function isJunk(path) {
  return path.split('/').slice(0, -1).includes('__pycache__') || ['.DS_Store', 'Thumbs.db', 'desktop.ini'].includes(posix.basename(path)) || /(?:\.(?:pyc|pyo|orig|rej)|~)$/u.test(path);
}

export function isCredential(path) {
  const name = posix.basename(path);
  if (['.env.example', '.env.sample'].includes(name) || /^\.env\..*\.example$/u.test(name) || name.endsWith('.pub')) return false;
  return name === '.env' || name.startsWith('.env.') || /\.(?:pem|p12|pfx|jks|keystore)$/u.test(name) || /^id_(?:rsa|dsa|ecdsa|ed25519)$/u.test(name);
}

export function isSelectedText(path) {
  return /\.(?:cfg|css|html|ini|js|json|jsonc|jsx|md|mjs|py|sh|toml|ts|tsx|txt|xml|yaml|yml)$/u.test(path) || ['.editorconfig', '.gitattributes', '.gitignore'].includes(posix.basename(path)) || /^\.githooks\/[^/]+$/u.test(path);
}

export function renderSnapshot(files) {
  const present = new Set(files);
  present.add(snapshotPath);
  const paths = components([...present]).map(path => present.has(path) ? path : `${path}/`);
  return '# Generated by node tools/check-repository-policy.mjs --write-snapshot\n# Regenerate after intentional repository structure changes.\n\n' + paths.join('\n') + '\n';
}

export function checkRepository(root, { writeSnapshot = false } = {}) {
  const files = repositoryFiles(root);
  assertSafeInputs(root, files);
  const findings = [];
  for (const file of requiredFiles) {
    if (!files.includes(file) || !lstatSync(resolve(root, file)).isFile()) findings.push(`${file}: required root file is missing`);
  }
  for (const path of components(files)) {
    if (!validName(path, files.includes(path))) findings.push(`${path}: invalid path name`);
  }
  for (const file of files) {
    if (isJunk(file)) findings.push(`${file}: junk artifact is not allowed`);
    if (isCredential(file)) findings.push(`${file}: credential-shaped filename is not allowed`);
    if (!isSelectedText(file)) continue;
    let content;
    try { content = decoder.decode(readFileSync(resolve(root, file))); }
    catch (error) { findings.push(`${file}: cannot read UTF-8 text (${error.message})`); continue; }
    if (content && !content.endsWith('\n')) findings.push(`${file}: missing final newline`);
  }
  const expected = renderSnapshot(files);
  if (writeSnapshot) {
    if (findings.length === 0) writeFileSync(resolve(root, snapshotPath), expected);
  } else if (!files.includes(snapshotPath) || readFileSync(resolve(root, snapshotPath), 'utf8') !== expected) {
    findings.push(`${snapshotPath}: snapshot differs; review intentional changes and run node tools/check-repository-policy.mjs --write-snapshot`);
  }
  return findings;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.length && (args.length !== 1 || args[0] !== '--write-snapshot')) throw new Error('Usage: node tools/check-repository-policy.mjs [--write-snapshot]');
    const findings = checkRepository(process.cwd(), { writeSnapshot: args.length === 1 });
    for (const finding of findings) console.error(finding);
    process.exitCode = findings.length ? 1 : 0;
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
